namespace WarcraftMod.Core;

/// <summary>
/// Волны открытия рас. Раса называет номер своей волны, а не своё место в очереди —
/// и это главное отличие от прежней схемы.
///
/// Очередь «каждая следующая раса на 12 уровней дороже» не пережила бы рост мода:
/// при трёх десятках рас последняя уехала бы за общий уровень 450, то есть за сотни
/// часов игры. Волна вмещает сколько угодно рас разом, поэтому новые расы дописываются
/// в существующие волны и порог не растёт вовсе.
///
/// Заодно волна даёт игроку выбор: открывается не одна раса, а несколько сразу.
/// </summary>
public static class Unlocks
{
    /// <summary>
    /// Общий уровень для каждой волны. Нулевая — стартовые расы, доступные сразу.
    /// Шаг между волнами растёт (25, +30, +40, +50, +60, +70, +80): новизна должна
    /// приходить часто в начале и оставаться событием в конце.
    /// </summary>
    private static readonly int[] TierLevels = [0, 25, 55, 95, 145, 205, 275, 355];

    /// <summary>Порог волны. Номера сверх таблицы продолжают её шагом в 80 уровней.</summary>
    public static int Tier(int tier)
    {
        if (tier <= 0) return 0;

        return tier < TierLevels.Length
            ? TierLevels[tier]
            : TierLevels[^1] + (tier - TierLevels.Length + 1) * 80;
    }
}

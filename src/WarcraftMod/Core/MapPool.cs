namespace WarcraftMod.Core;

/// <summary>
/// Карта из пула быстрой смены.
/// </summary>
/// <param name="Name">Имя карты на сервере — оно же видно в меню.</param>
/// <param name="WorkshopId">Номер в Workshop. 0 — карта стоковая, лежит в csgo\maps.</param>
public sealed record MapEntry(string Name, long WorkshopId = 0)
{
    /// <summary>
    /// Команда, которой сервер переключается на эту карту. Воркшопную по имени не взять:
    /// в <c>csgo\maps</c> её файла нет, и грузится она только по номеру.
    /// </summary>
    public string ChangeCommand => WorkshopId > 0 ? $"host_workshop_map {WorkshopId}" : $"map {Name}";
}

/// <summary>
/// Пул карт для меню <c>!map</c>. Правится здесь и только здесь.
///
/// Воркшопные карты должны быть скачаны игровым клиентом на этой же машине:
/// своей копии сервер не держит и берёт то, что скачал клиент. Отписка в клиенте
/// сломает переключение.
/// </summary>
public static class MapPool
{
    /// <summary>
    /// Порядок — по частоте использования, а не по алфавиту: курсор при открытии меню
    /// всегда встаёт на первую строку, и промах по ней должен быть наименее болезненным.
    /// </summary>
    /// <remarks>
    /// <para>
    /// awp_lego_2 стоит первой с 17.08.2026: боевой сервер переведён на неё, и после
    /// матча вернётся именно на неё — поэтому она же должна быть первой строкой меню.
    /// Причина переезда не в карте, а во входе: «lego» — слово, которое набирают в
    /// поиске, и онлайн на такие серверы приходит сам. Мод от карты не зависит вовсе,
    /// он к ней просто прилагается. Остальные карты оставлены как были: пул — это
    /// способ увести сервер в сторону руками, и сужать его до одной строки значит
    /// отнимать эту возможность.
    /// </para>
    /// <para>
    /// Номера сверять запросом к API Steam, а не тем, что карта открывается у себя:
    /// исчезнувшая из воркшопа карта грузится у того, кто скачал её раньше, и молча
    /// ломается у всех остальных. Ровно так отпал <b>прежний</b> номер awp_lego_2
    /// (3146105097): на машине разработки лежит, в воркшопе его нет (<c>result 9</c>).
    /// Живой перезалив той же карты — 3367343580, проверен 17.08.2026:
    /// <c>result 1</c>, <c>banned 0</c>, 61 МБ, 161 590 подписок. Мёртвый номер сюда
    /// возвращать нельзя, как бы исправно карта ни открывалась у себя.
    /// </para>
    /// </remarks>
    public static readonly IReadOnlyList<MapEntry> All =
    [
        // Стартовая карта боевого сервера. 61 МБ — на входе игрок ждёт секунды,
        // а не минуту; для сервера, который борется за первого зашедшего, это важнее
        // разнообразия геометрии.
        new("awp_lego_2", 3367343580),
        // Assault в версии 1.6: 49 МБ против 300-440 у остальных портов, и геометрия
        // проще — для мода про перемещение это плюс, а не потеря.
        new("cs_assault_classic", 3110659358),
        new("de_rats_room", 3565920324),
        new("opc_rats", 3372778412),
        new("ar_pool_day"),
        new("ar_baggage"),
        new("de_dust2"),
    ];
}

using System.Text.Json;
using WarcraftMod.Core;

namespace WarcraftMod.Config;

/// <summary>Настройки мода. Лежат рядом с плагином в warcraft_config.json.</summary>
public sealed class WarcraftConfig
{
    public int XpPerKill { get; set; } = 30;
    public int XpHeadshotBonus { get; set; } = 10;
    public int XpKnifeBonus { get; set; } = 30;
    public int XpPerAssist { get; set; } = 15;
    public int XpRoundWin { get; set; } = 15;

    /// <summary>
    /// Опыт всем, кто отыграл раунд, независимо от исхода и от того, когда погиб.
    /// Это пол прогрессии: без него слабый игрок получал вчетверо меньше сильного и уходил
    /// задолго до первой новой расы, а публичный сервер держится как раз на таких игроках.
    /// </summary>
    public int XpPerRound { get; set; } = 20;

    /// <summary>
    /// Опыт за то, что дожил до конца раунда. Награда ровно за то, ради чего сделаны
    /// Ночные Эльфы, Оборотень и Разведчик: мод про уклонение и обман, а опыт до сих пор
    /// давали только за стрельбу.
    /// </summary>
    public int XpSurvived { get; set; } = 10;

    /// <summary>
    /// Как часто сбрасывать прогресс на диск, в секундах. Столько же максимум теряется
    /// при жёстком падении сервера. Взятые уровни, конец раунда, выход игрока и выдача
    /// расы пишутся отдельно и сразу, не дожидаясь этого таймера.
    /// </summary>
    public float SaveIntervalSeconds { get; set; } = 30f;

    /// <summary>Открывать меню выбора расы новичку при первом заходе.</summary>
    public bool ShowRaceMenuOnFirstJoin { get; set; } = true;

    /// <summary>
    /// Сколько длится подготовка последнего раунда — того, в начале которого идёт
    /// голосование за следующую карту. 0 — не голосовать вовсе.
    ///
    /// Голосуют именно во фризтайме: игрок в нём и так обездвижен, поэтому меню,
    /// которое его замораживает, не отнимает у него ни секунды игры.
    /// </summary>
    public float MapVoteFreezeSeconds { get; set; } = 12f;

    /// <summary>
    /// Через сколько секунд бездействия переносить игрока в зрители. 0 — не переносить.
    /// Считается только время в живом состоянии: мёртвый двигаться не может, и записывать
    /// ему бездействие было бы наказанием за смерть.
    /// </summary>
    public float AfkSeconds { get; set; } = 300f;

    /// <summary>
    /// На сколько единиц ниже самой низкой точки возрождения проходит дно карты.
    /// Тот, кто провалился ниже и не касается земли, возвращается на спавн своей
    /// команды. 0 — не возвращать вовсе.
    ///
    /// Нужно это не всей игре, а способностям, которые подбрасывают: на awp_lego
    /// Батутом и прыжками перелетают белые стены вокруг арены и застревают под миром
    /// до конца раунда — урон от падения на сервере выключен, и смерть оттуда не
    /// выпускает. Запас считается от спавнов, а не задаётся числом на карту, чтобы
    /// работало и на остальных картах пула без правки под каждую.
    /// </summary>
    public float OutOfBoundsDropUnits { get; set; } = 512f;

    /// <summary>
    /// Забор по горизонтали: имя карты → на сколько юнитов дальше самой крайней точки
    /// возрождения ещё можно отходить. Кто вышел за эту рамку, возвращается на спавн
    /// сразу, даже стоя на земле. Карты в списке нет — забора на ней нет вовсе.
    ///
    /// Список именно по картам, а не одно число на всё: за коробкой спавнов у каждой
    /// карты своё. На awp_lego за стенами арены выстроена вторая, маленькая — попасть
    /// туда можно только прыжком расы, и играть там нечего. А на de_dust2 или rats
    /// та же рамка выкидывала бы людей с честных мест.
    ///
    /// Число подбирается замером: <c>css_wcpos</c> печатает, на сколько вы сейчас
    /// вышли за коробку спавнов. Встать в дальнем углу арены, встать на чужой площадке —
    /// и взять что-то между.
    /// </summary>
    public Dictionary<string, float> OutOfBoundsFence { get; set; } = new();

    /// <summary>
    /// Через сколько секунд повторить вошедшему подсказку про меню.
    /// Подсказка личная, а не общая по серверу: она нужна тому, кто только зашёл,
    /// а не всем подряд каждые десять минут.
    /// </summary>
    public float HintRepeatSeconds { get; set; } = 120f;

    /// <summary>
    /// Сколько раз повторить подсказку после входа. 0 — не повторять. Приветствие при
    /// входе сюда не считается, поэтому единица — это два показа всего.
    /// Зашедший в разгар боя первую строку часто не замечает: повтор догоняет его,
    /// когда он уже осмотрелся, и на этом заканчивается — постоянного спама нет.
    /// </summary>
    public int HintRepeats { get; set; } = 1;

    /// <summary>
    /// Сколько минут идёт раунд. 0 — не вмешиваться, время останется за конфигом сервера.
    ///
    /// Мод выставляет его сам, потому что воркшоп-карты задают своё время на загрузке —
    /// уже после конфигов, и файлом их не переспорить. opc_rats ставит себе десять минут.
    /// </summary>
    public float RoundTimeMinutes { get; set; } = 2.5f;

    /// <summary>
    /// Сколько секунд длится конец матча — от последнего раунда до перезапуска.
    /// 0 — не вмешиваться, останется движковое умолчание в 15 секунд.
    ///
    /// Умолчание рассчитано на турнирный матч, где итог разглядывают. Здесь разглядывать
    /// нечего: счёт держится минуту, а мод к этому времени уже выбрал следующую карту
    /// своим голосованием и меняет её сам. Длинный экран итогов — это просто пауза,
    /// в которую игроки уходят с сервера.
    /// </summary>
    public float MatchEndSeconds { get; set; } = 5f;

    /// <summary>
    /// Ссылка на Discord: строка приветствия при входе и пункт меню. Пустая строка убирает
    /// и то, и другое.
    ///
    /// Вынесена в конфиг, а не зашита в код, по одной причине: сервер обновляется руками
    /// через SFTP, и смена адреса не должна стоить пересборки плагина. Пишется без
    /// «https://» — кликнуть ссылку в CS2 всё равно нельзя, её перепечатывают руками,
    /// и лишние восемь символов тут работают против нас.
    /// </summary>
    public string DiscordUrl { get; set; } = "";

    /// <summary>
    /// Событие озвучки для того, кто зашёл впервые. Пустая строка выключает.
    ///
    /// Имя события, а не путь к файлу: движок играет только то, что описано в
    /// `soundevents_addon.vsndevts` внутри воркшоп-аддона, и знает это описание по имени.
    /// В настройках, а не в коде, по той же причине, что и ссылка на Discord: сервер
    /// обновляется руками через SFTP, и правка имени не должна стоить пересборки плагина.
    ///
    /// Если аддон не подключён или имя написано с ошибкой, движок молчит — без ошибки
    /// и без записи в лог. Проверять только командой `css_wcsound <имя>`.
    /// </summary>
    public string WelcomeSoundNew { get; set; } = "";

    /// <summary>
    /// События озвучки для возвращающегося. Список, а из него берётся случайное:
    /// одна и та же секундная реплика каждый вечер приедается быстрее всего, а лишняя
    /// запись в аддоне весит копейки. Пустой список выключает.
    /// </summary>
    public string[] WelcomeSoundReturning { get; set; } = [];

    /// <summary>
    /// Сколько часов не повторять приветствие возвращающемуся. 0 — играть каждый заход.
    ///
    /// Сутки взяты не наугад: люди перезаходят по три раза за вечер — смена карты, вылет,
    /// перезапуск сервера, — и приветствие на каждый вход из радушия превращается
    /// в раздражитель быстрее, чем успевает понравиться. Новичка это не касается:
    /// его реплика играет один раз в жизни и кулдаунов не знает.
    /// </summary>
    public float WelcomeSoundHours { get; set; } = 24f;

    /// <summary>Громкость приветствия. Речь глушить не стоит, но подстройка нужна на месте.</summary>
    public float WelcomeSoundVolume { get; set; } = 1f;

    /// <summary>
    /// Рисовать меню надписями в мире, привязанными к модели рук. false — вернуться
    /// к тексту в центре экрана.
    ///
    /// Это лечение мигания. Текст в центре экрана мод шлёт клиенту каждый кадр, и панель,
    /// которой он рисуется, гаснет от любой перерисовки интерфейса — отсюда побеление
    /// примерно раз в секунду. Надпись в мире уходит клиенту один раз и дальше едет
    /// за камерой сама. Запасной способ оставлен на случай, если привязаться не выйдет.
    /// </summary>
    public bool MenuInWorldText { get; set; } = true;

    /// <summary>
    /// Чем писать меню в центр экрана: 0 — панель Danger Zone (с разметкой и цветами),
    /// 1 — обычный текст движка, 2 — он же другим стилем.
    ///
    /// Разные механизмы, а не варианты одного. Панель в бою белеет сама, и ни частота
    /// отправки, ни длительность показа этого не лечат — проверено подбором вживую
    /// 16.08.2026. Способы 1 и 2 идут мимо неё, но цветов не понимают.
    /// </summary>
    public int MenuCenterStyle { get; set; } = 0;

    /// <summary>
    /// Слать ли меню с разметкой — цвета и размеры шрифта. Панель разметку понимает точно,
    /// про остальные два способа заранее неизвестно: если не поймут, теги будут видны
    /// как есть, и тогда сюда надо поставить false.
    /// </summary>
    public bool MenuCenterMarkup { get; set; } = true;

    /// <summary>
    /// Писать ли надписи мода в центр экрана: прибавку опыта и сообщения способностей.
    /// false — мод в центр не пишет ничего, кроме самого меню. Ручка для разбора мигания.
    /// </summary>
    public bool ShowCenterMessages { get; set; } = true;

    /// <summary>
    /// Шрифт меню. Имя движок берёт из своего набора, и проверить его можно только на глаз:
    /// незнакомое имя он молча заменяет своим. Годные варианты, от жирного к тонкому:
    /// «Arial Black», «Stratum2 Black», «Arial Bold», «Arial».
    /// </summary>
    public string MenuFontName { get; set; } = "Arial Black";

    /// <summary>Размер шрифта меню. Подбирается только глазами, поэтому вынесен сюда.</summary>
    public float MenuFontSize { get; set; } = 32f;

    /// <summary>
    /// Тёмная подложка под строками меню. На пёстрой карте без неё текст теряется,
    /// зато с ней панель заметнее загораживает обзор.
    /// </summary>
    public bool MenuBackground { get; set; } = false;

    /// <summary>
    /// Тень под строками меню: каждая строка рисуется дважды, тёмным двойником и поверх
    /// него цветной надписью. Так текст читается на любом фоне, и в отличие от подложки
    /// не появляется коробок. Цена — вдвое больше сущностей на открытое меню.
    /// </summary>
    public bool MenuShadow { get; set; } = true;

    /// <summary>
    /// Сдвиг меню вправо от центра, в единицах мира. Отрицательное — влево. Ноль означает
    /// «ровно перед игроком»: мод сам считает ширину списка и ставит его посередине.
    /// </summary>
    public float MenuShiftRight { get; set; } = 0f;

    /// <summary>Сдвиг меню вверх от центра, в единицах мира. Ноль — по высоте взгляда.</summary>
    public float MenuShiftUp { get; set; } = 0f;

    /// <summary>
    /// Вести меню за камерой. true — оно всегда перед глазами; сервер переставляет его
    /// каждый кадр, и из-за сглаживания сущностей на клиенте оно чуть подрагивает.
    /// false — висит неподвижно там, где открыли, и уходит с экрана, стоит отвернуться.
    ///
    /// Пробовали третий путь — привязку к модели игрока: дрожи там нет вовсе, но надпись
    /// идёт за телом, а тело в CS2 доворачивается за взглядом с задержкой и рывком.
    /// </summary>
    public bool MenuFollowView { get; set; } = true;

    /// <summary>
    /// Запретить ультимейты в пистолетных раундах — первых раундах каждой половины.
    /// Там у всех одинаково пусто в карманах, и ульта решала бы раунд в одиночку.
    /// </summary>
    public bool DisableUltimatesInPistolRounds { get; set; } = true;

    /// <summary>
    /// Выдавать ли расам свой облик. false — все ходят в обычных агентах из своего инвентаря.
    ///
    /// Отдельный выключатель нужен потому, что модель — единственное, что игрок видит
    /// в бою раньше ника: если облик окажется неудачным или кастомный аддон отвалится,
    /// вернуть обычный вид надо одной правкой в файле, а не пересборкой плагина.
    /// </summary>
    public bool UseRaceModels { get; set; } = true;

    /// <summary>
    /// Чем заменить облик по умолчанию. Ключ — идентификатор расы (<c>orc</c>, <c>undead</c>…),
    /// внутри пути к моделям: <c>CT</c> и <c>T</c>. Пустая строка — оставить расе обычный вид.
    ///
    /// Вынесено в файл по той же причине, что и внешний вид меню: подобрать облик можно
    /// только глазами, а боевой сервер обновляется руками через SFTP. Сюда же вписываются
    /// пути кастомных моделей из воркшоп-аддона, когда он появится, — код при этом
    /// не трогается вовсе.
    ///
    /// <code>
    /// "RaceModels": {
    ///   "orc": { "CT": "characters/models/orc/orc.vmdl", "T": "characters/models/orc/orc.vmdl" }
    /// }
    /// </code>
    /// </summary>
    public Dictionary<string, RaceModelPair> RaceModels { get; set; } = [];

    /// <summary>
    /// SteamID64 доверенных игроков — им открыта админка <c>!admin</c>: смена карты, кик, бан, мут.
    /// Пишутся строками: JSON-число такой длины теряет точность.
    ///
    /// Это единственный способ получить права. Флага, включавшего отладочные команды всем,
    /// больше нет — сами команды из мода убраны, чтобы на публике их нельзя было включить
    /// ни по ошибке, ни намеренно.
    /// </summary>
    public List<string> Admins { get; set; } = [];

    public static WarcraftConfig LoadOrCreate(string path)
    {
        try
        {
            if (File.Exists(path))
            {
                var config = JsonSerializer.Deserialize<WarcraftConfig>(File.ReadAllText(path));
                if (config is not null) return config;
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"[WarcraftMod] Конфиг повреждён ({ex.Message}), беру значения по умолчанию.");
            return new WarcraftConfig();
        }

        var created = new WarcraftConfig();
        try
        {
            File.WriteAllText(path, JsonSerializer.Serialize(created, new JsonSerializerOptions { WriteIndented = true }));
        }
        catch (Exception ex)
        {
            Console.WriteLine($"[WarcraftMod] Не удалось создать конфиг: {ex.Message}");
        }

        return created;
    }
}
